"""Rebuild knowledge/axe-rules.md from axe-core's own rule list.

Usage:
    python tools/build_axe_rules.py --axe-dir <path to node_modules/axe-core>

The rule IDs and tags come from axe-core (`axe.getRules()`), run with Node.js. The
criterion titles, levels, and entry paths come from knowledge/INDEX.md, so nothing is
written from memory. Rules with no WCAG tag are marked best practice. A few best
practice rules point to the html/ or aria/ entry that covers the topic (BEST_PRACTICE
below). Rule descriptions are linked to Deque, never copied (principle 12).

Find axe-core after one `npx --yes @axe-core/cli` run, in the npm cache:
    <npm cache>/_npx/<hash>/node_modules/axe-core
Set DOCTOR_A11Y_NODE_DIR if Node.js is not on PATH.
"""

import argparse
import datetime
import json
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Best-practice rules (no WCAG tag) and the entry that covers the topic.
BEST_PRACTICE = [
    (r"^(region|landmark-.*|bypass)$", "html/landmarks.md"),
    (r"^(heading-order|page-has-heading-one|empty-heading|empty-table-header)$", "html/headings.md"),
    (r"^(image-redundant-alt)$", "content/alt-text.md"),
    (r"^(table-duplicate-name|scope-attr-valid|td-has-header)$", "html/tables.md"),
    (r"^(label-title-only)$", "html/forms.md"),
    (r"^(aria-.*|presentation-role-conflict)$", "aria/aria-in-html.md"),
    (r"^(tabindex|focus-order-semantics|accesskeys)$", "aria/using-aria.md"),
    (r"^(skip-link)$", "html/landmarks.md"),
    (r"^(meta-viewport-large)$", "design/reflow.md"),
    (r"^(frame-tested|frame-title-unique)$", "html/landmarks.md"),
]


def find_node():
    folder = os.environ.get("DOCTOR_A11Y_NODE_DIR")
    for cand in ([os.path.join(folder, "node.exe"), os.path.join(folder, "node")] if folder else []):
        if os.path.exists(cand):
            return cand
    return shutil.which("node")


def read_index():
    """Criterion number -> (title, level, entry path) from knowledge/INDEX.md."""
    rows = {}
    for line in open(os.path.join(ROOT, "knowledge", "INDEX.md"), encoding="utf-8"):
        m = re.match(r"\|\s*(\d+\.\d+\.\d+)\s*\|\s*([^|]+?)\s*\|\s*(A|AA)\s*\|\s*`([^`]+)`", line)
        if m:
            rows[m.group(1)] = (m.group(2), m.group(3), m.group(4))
    return rows


def sc_from_tag(tag):
    m = re.fullmatch(r"wcag(\d)(\d)(\d+)", tag)
    return f"{m.group(1)}.{m.group(2)}.{m.group(3)}" if m else None


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--axe-dir", required=True)
    ap.add_argument("--out", default=os.path.join(ROOT, "knowledge", "axe-rules.md"))
    args = ap.parse_args(argv)
    node = find_node()
    if not node:
        print("node not found; set DOCTOR_A11Y_NODE_DIR")
        return 2
    js = ("const a=require(process.argv[1]);"
          "console.log(JSON.stringify({version:a.version,rules:a.getRules()}))")
    out = subprocess.run([node, "-e", js, args.axe_dir], capture_output=True, text=True, check=True).stdout
    data = json.loads(out)
    version, rules = data["version"], sorted(data["rules"], key=lambda r: r["ruleId"])
    major_minor = ".".join(version.split(".")[:2])
    index = read_index()
    today = datetime.date.today().isoformat()

    rows, unmapped = [], []
    for r in rules:
        rid, tags = r["ruleId"], r["tags"]
        flags = [t for t in ("experimental", "deprecated", "review-item") if t in tags]
        scs = [s for s in (sc_from_tag(t) for t in tags) if s]
        cells = []
        for sc in scs:
            if sc in index:
                title, level, entry = index[sc]
                cells.append(f"{sc} {title} ({level}): `{entry}`")
            elif "wcag2a-obsolete" in tags and sc == "4.1.1":
                cells.append("4.1.1, obsolete in WCAG 2.2: no entry, not a finding")
            else:
                # Not in INDEX's Level A and AA table: beyond our target. Say so; do not guess the level.
                cells.append(f"{sc}: not a Level A or AA criterion in `knowledge/INDEX.md`, so beyond our target; no entry")
        if not scs:
            entry = next((e for pat, e in BEST_PRACTICE if re.match(pat, rid)), None)
            cells.append("best practice, not a WCAG finding" + (f": `{entry}`" if entry else ""))
        note = ", ".join(flags)
        link = f"https://dequeuniversity.com/rules/axe/{major_minor}/{rid}"
        rows.append(f"| `{rid}` | {'; '.join(cells)} | {note} | [Deque]({link}) |")

    body = f"""# axe-core rules and the entries they map to

- Source: axe-core {version}, the rule IDs and tags from `axe.getRules()`; Deque's rule descriptions, linked per rule. Tier 3 (`knowledge/SOURCES.md`, "Deque axe rule descriptions").
- Criterion titles, levels, and entries: `knowledge/INDEX.md`.
- Generated by `tools/build_axe_rules.py` on {today}. Rebuild it when axe-core updates; do not edit the table by hand.

## Status and reporting

A rule's WCAG tags say which criterion axe connects it to; they are axe's mapping, tier 3, not the criterion. Before writing a finding from an axe result, open the entry named here and grade it at that entry's confidence. A violation is a lead the verifier confirms by reading the code, and a clean run is never a pass. Rules marked best practice are advice, never a WCAG finding. Criteria not in the Level A and AA table of `knowledge/INDEX.md`, and the obsolete 4.1.1, are beyond our target. Rules marked experimental may not run by default, and a review item is a prompt for a person.

## The table

| Rule | WCAG criteria and our entries | Flags | Description |
|---|---|---|---|
""" + "\n".join(rows) + "\n"
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(body)
    print(f"axe-core {version}: {len(rules)} rules written to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
